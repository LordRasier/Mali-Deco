import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { CheckoutSummary } from '../src/components/CheckoutSummary';
import type { CartState } from '../src/hooks/useCart';
const cart = { items:[{productId:'p',variantId:'v',quantity:2,product:{name:'Mesa'},variant:{name:'Roble',priceMinor:100,currency:'ARS'}}], totals:{ARS:200n}, unresolved:false } as unknown as CartState;
const selected = {id:'o',carrierName:'Correo',serviceName:'Casa',serviceCode:'home',amountMinor:'50',currency:'ARS'};
const render = (valid:boolean, value=cart) => renderToStaticMarkup(React.createElement(CheckoutSummary,{cart:value,selected,valid,pickupReady:true,disabled:false,sending:false}));
const active=render(true);
assert.match(active,/Mesa/); assert.match(active,/Roble/); assert.match(active,/Subtotal/); assert.match(active,/Total estimado/);
assert.doesNotMatch(render(false),/Total estimado/);
const mixed = {...cart, totals:{ARS:200n,USD:100n}};
assert.doesNotMatch(render(true,mixed),/Total estimado/);
assert.match(render(false), /<button type="submit" disabled=""/);
assert.match(render(true,mixed), /<button type="submit" disabled=""/);
assert.doesNotMatch(active, /<button type="submit" disabled=""/);
const missing = renderToStaticMarkup(React.createElement(CheckoutSummary,{cart,selected:undefined,valid:false,pickupReady:true,disabled:true,sending:false}));
assert.match(missing, /<button type="submit" disabled=""/);
